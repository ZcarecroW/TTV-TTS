// Exports the icons listed in icons.json from the author's licensed Nucleo
// library into packages/ui/src/icons/nucleo.ts (inline SVG bodies, no
// requests), and the documentation-only ones in docs-icons.json (search,
// system logos) into docs/site/icons.gen.mjs, so the apps don't carry them.
// Needs the author's Nucleo setup (the nucleo-library CLI); the generated
// files are part of TTV-TTS and must not be extracted or redistributed as an
// icon set.
//   npm run icons            (NUCLEO_CLI=<path to nucleo.mjs> to override)
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const cli = process.env.NUCLEO_CLI ?? join(homedir(), ".claude", "skills", "nucleo-library", "scripts", "nucleo.mjs");
const load = (f) => Object.entries(JSON.parse(readFileSync(join(here, f), "utf8"))).filter(([k]) => !k.startsWith("_"));
const app = load("icons.json");
const docs = load("docs-icons.json");
const total = new Set([...app, ...docs].map(([, spec]) => spec)).size;
if (total > 100) throw new Error(`${total} icons: the Nucleo license allows at most 100 in a public repo`);

const NOTICE = `// Generated by scripts/icons/export.mjs from the Nucleo icon library (nucleoapp.com).
// Nucleo icons are licensed to the TTV-TTS author and are NOT covered by the MIT license
// of this project: they may be used as part of TTV-TTS, but not extracted or redistributed.
/* eslint-disable */`;

/** One `  Alias: [viewBox, body], // spec` line per entry (one CLI call per set). */
function exportSet(entries) {
  const out = mkdtempSync(join(tmpdir(), "ttv-icons-"));
  try {
    execFileSync(process.execPath, [cli, "get", ...entries.map(([, spec]) => spec), "--format", "svg", "--out", out], { stdio: ["ignore", "ignore", "inherit"] });
    const files = new Set(readdirSync(out));
    return entries.map(([alias, spec]) => {
      const name = spec.split("/")[0];
      const file = files.has(`${name}.svg`) ? `${name}.svg` : [...files].find((f) => f.startsWith(`${name}-`));
      if (!file) throw new Error(`${alias}: ${spec} was not exported`);
      const raw = readFileSync(join(out, file), "utf8");
      const viewBox = raw.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 24 24";
      const body = raw
        .replace(/^[\s\S]*?<svg[^>]*>/, "")
        .replace(/<\/svg>\s*$/, "")
        // The secondary color follows the theme accent (.nc-c2 in style.css).
        .replace(/\sdata-color="color-2"/g, ' class="nc-c2"')
        .replace(/>\s+</g, "><")
        .trim();
      return `  ${alias}: [${JSON.stringify(viewBox)}, ${JSON.stringify(body)}], // ${spec}`;
    });
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}

const lines = exportSet(app);
const file = `${NOTICE}\nexport const nucleo: Record<string, [string, string]> = {\n${lines.join("\n")}\n};\n`;
const dir = join(root, "packages", "ui", "src", "icons");
writeFileSync(join(dir, "nucleo.ts"), file);
// index.ts: everything up to the first export stays, the exports follow the manifest.
const index = readFileSync(join(dir, "index.ts"), "utf8");
const head = index.slice(0, index.indexOf("export const "));
writeFileSync(join(dir, "index.ts"), head + app.map(([alias]) => `export const ${alias} = icon("${alias}");`).join("\n") + "\n");

const docLines = exportSet(docs);
writeFileSync(join(root, "docs", "site", "icons.gen.mjs"), `${NOTICE}\n// Only on the documentation website.\nexport const docsIcons = {\n${docLines.join("\n")}\n};\n`);
console.log(`exported ${lines.length} app icons (${(file.length / 1024).toFixed(1)} KB) and ${docLines.length} docs icons; ${total} of 100 allowed`);
