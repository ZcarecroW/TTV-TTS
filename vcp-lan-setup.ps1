<#
.SYNOPSIS
  Makes Voice Creator Pro (VCP) reachable from other PCs in your LAN - permanently.
  Part of the TTV-TTS pack by ZcarecroW (twitch.tv/zcarecrow) - MIT License.

.DESCRIPTION
  Run this ON THE PC THAT RUNS VOICE CREATOR PRO (only needed for a two-PC setup).

  VCP's HTTP API only listens on 127.0.0.1 (this PC). This script:
    1. adds a Windows port proxy  0.0.0.0:<ListenPort>  ->  127.0.0.1:<VcpPort>
    2. makes sure the "IP Helper" service (which runs the port proxy) starts automatically
    3. adds an inbound firewall rule for <ListenPort> in the group "<FirewallGroup>"
    4. registers a scheduled task "VCP LAN Access" that re-checks 1-3 at every boot/logon
    5. prints a status report incl. the baseUrl to put into ttv-tts.html

  Malwarebytes Windows Firewall Control (WFC) users: WFC's "Secure Rules" deletes every
  firewall rule that is not in an authorized group. Add the group name (default: VCP) under
  WFC -> Security -> "Define here a new authorized group" BEFORE running this script.

.PARAMETER ListenPort   Port other PCs connect to (default 8101). Use this port in ttv-tts.html.
.PARAMETER VcpPort      Port of the VCP HTTP API on this PC (default 8100, see VCP settings).
.PARAMETER FirewallGroup Group name of the firewall rule (default VCP).
.PARAMETER Check        Only print the status report, change nothing.
.PARAMETER Uninstall    Remove task, firewall rule, port proxy and helper files.
.PARAMETER NoPause      Don't wait for Enter at the end.

.EXAMPLE
  Right-click the file -> "Run with PowerShell"   (it asks for admin rights by itself)
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\vcp-lan-setup.ps1 -Check
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\vcp-lan-setup.ps1 -ListenPort 8201 -VcpPort 8200
#>
[CmdletBinding()]
param(
  [int]$ListenPort = 8101,
  [int]$VcpPort = 8100,
  [string]$FirewallGroup = 'VCP',
  [switch]$Check,
  [switch]$Uninstall,
  [switch]$NoPause
)

$ErrorActionPreference = 'Stop'
$TaskName  = 'VCP LAN Access'
$RuleName  = 'VCP-API-Proxy'
$HelperDir = Join-Path $env:ProgramData 'VCP-LAN'
$Helper    = Join-Path $HelperDir 'ensure.ps1'

function Write-Step([string]$text) { Write-Host "`n== $text" -ForegroundColor Cyan }
function Write-Ok([string]$text)   { Write-Host "  [OK]   $text" -ForegroundColor Green }
function Write-Warn([string]$text) { Write-Host "  [!]    $text" -ForegroundColor Yellow }
function Write-Bad([string]$text)  { Write-Host "  [X]    $text" -ForegroundColor Red }
function Write-Info([string]$text) { Write-Host "         $text" }
function Wait-End { if (-not $NoPause -and $Host.Name -eq 'ConsoleHost') { [void](Read-Host "`nPress Enter to close") } }

# ---------------------------------------------------------------- admin rights
$principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
  Write-Host 'Administrator rights are required - asking Windows to restart this script elevated ...' -ForegroundColor Yellow
  $argList = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', "`"$PSCommandPath`"")
  foreach ($kv in $PSBoundParameters.GetEnumerator()) {
    if ($kv.Value -is [System.Management.Automation.SwitchParameter]) { if ($kv.Value.IsPresent) { $argList += "-$($kv.Key)" } }
    else { $argList += "-$($kv.Key)"; $argList += "$($kv.Value)" }
  }
  Start-Process -FilePath (Get-Process -Id $PID).Path -Verb RunAs -ArgumentList $argList
  exit
}

# ---------------------------------------------------------------- helper script (runs at every boot)
$ensureTemplate = @'
# Generated by vcp-lan-setup.ps1 (TTV-TTS pack). Keeps Voice Creator Pro reachable in the LAN:
# port proxy 0.0.0.0:__LISTEN__ -> 127.0.0.1:__TARGET__, IP Helper service, firewall rule in group "__GROUP__".
$port = __LISTEN__; $target = __TARGET__; $group = '__GROUP__'
$pp = (netsh interface portproxy show v4tov4) -join "`n"
if ($pp -notmatch "0\.0\.0\.0\s+$port\s+127\.0\.0\.1\s+$target") {
  netsh interface portproxy add v4tov4 listenaddress=0.0.0.0 listenport=$port connectaddress=127.0.0.1 connectport=$target | Out-Null
}
Set-Service iphlpsvc -StartupType Automatic
Start-Service iphlpsvc
$rule = Get-NetFirewallRule -Name '__RULE__' -ErrorAction SilentlyContinue
if ($rule -and $rule.Group -ne $group) { Remove-NetFirewallRule -Name '__RULE__'; $rule = $null }
if (-not $rule) {
  New-NetFirewallRule -Name '__RULE__' -DisplayName 'Voice Creator Pro API Proxy' -Group $group -Direction Inbound -Protocol TCP -LocalPort $port -Action Allow -Profile Any | Out-Null
} else { Enable-NetFirewallRule -Name '__RULE__' }
'@

function Install-Lan {
  Write-Step "Installing (listen port $ListenPort -> VCP port $VcpPort, firewall group '$FirewallGroup')"
  New-Item -ItemType Directory -Force $HelperDir | Out-Null
  $ensure = $ensureTemplate.Replace('__LISTEN__', "$ListenPort").Replace('__TARGET__', "$VcpPort").Replace('__GROUP__', $FirewallGroup).Replace('__RULE__', $RuleName)
  Set-Content -Path $Helper -Value $ensure -Encoding ascii
  Write-Ok "Helper script written: $Helper"

  $action   = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$Helper`""
  $triggers = @((New-ScheduledTaskTrigger -AtStartup), (New-ScheduledTaskTrigger -AtLogOn))
  Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $triggers -User 'SYSTEM' -RunLevel Highest -Force | Out-Null
  Write-Ok "Scheduled task '$TaskName' registered (runs at every startup and logon)"

  & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $Helper
  Write-Ok 'Port proxy, IP Helper service and firewall rule applied'
  Write-Info 'Waiting 8 seconds (gives third-party firewall managers time to react) ...'
  Start-Sleep -Seconds 8
}

function Uninstall-Lan {
  Write-Step 'Uninstalling'
  if (Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue) { Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false; Write-Ok "Task '$TaskName' removed" }
  if (Get-NetFirewallRule -Name $RuleName -ErrorAction SilentlyContinue) { Remove-NetFirewallRule -Name $RuleName; Write-Ok "Firewall rule '$RuleName' removed" }
  try { netsh interface portproxy delete v4tov4 listenaddress=0.0.0.0 listenport=$ListenPort | Out-Null } catch { }
  Write-Ok "Port proxy on $ListenPort removed (if it existed)"
  if (Test-Path $HelperDir) { Remove-Item -Recurse -Force $HelperDir; Write-Ok "Folder $HelperDir removed" }
  Write-Info 'The IP Helper service is left running (Windows uses it for other things too).'
}

function Show-Status {
  Write-Step 'Status report'
  $problems = 0

  # 1. VCP itself
  $vcpListen = Get-NetTCPConnection -State Listen -LocalPort $VcpPort -ErrorAction SilentlyContinue
  if ($vcpListen) {
    $addr = ($vcpListen | Select-Object -ExpandProperty LocalAddress -Unique) -join ', '
    Write-Ok "VCP HTTP API listens on port $VcpPort ($addr)"
    if ($addr -match '0\.0\.0\.0|::') { Write-Info 'VCP already listens on all interfaces - the port proxy would not even be needed.' }
  } else {
    Write-Bad "Nothing listens on port $VcpPort - start Voice Creator Pro and enable the HTTP API (check the port in its settings)."
    $problems++
  }

  # 2. port proxy + IP Helper
  $pp = (netsh interface portproxy show v4tov4) -join "`n"
  if ($pp -match "0\.0\.0\.0\s+$ListenPort\s+127\.0\.0\.1\s+$VcpPort") { Write-Ok "Port proxy 0.0.0.0:$ListenPort -> 127.0.0.1:$VcpPort is configured" }
  else { Write-Bad "Port proxy for $ListenPort is missing"; $problems++ }
  $svc = Get-Service iphlpsvc -ErrorAction SilentlyContinue
  if ($svc -and $svc.Status -eq 'Running') { Write-Ok "IP Helper service running (start type: $($svc.StartType))" }
  else { Write-Bad 'IP Helper service (iphlpsvc) is not running - the port proxy does not work without it'; $problems++ }
  $proxyListen = Get-NetTCPConnection -State Listen -LocalPort $ListenPort -ErrorAction SilentlyContinue
  if ($proxyListen) { Write-Ok "Something listens on port $ListenPort" } else { Write-Bad "Nothing listens on port $ListenPort"; $problems++ }

  # 3. excluded port ranges (Hyper-V / WSL / Docker can reserve ports at boot)
  $excluded = netsh int ipv4 show excludedportrange protocol=tcp | Select-String '^\s*(\d+)\s+(\d+)'
  foreach ($m in $excluded) {
    $start = [int]$m.Matches[0].Groups[1].Value; $end = [int]$m.Matches[0].Groups[2].Value
    if ($ListenPort -ge $start -and $ListenPort -le $end) { Write-Bad "Port $ListenPort lies in a range reserved by Windows ($start-$end) - choose another -ListenPort"; $problems++ }
  }

  # 4. firewall
  $rule = Get-NetFirewallRule -Name $RuleName -ErrorAction SilentlyContinue
  if ($rule) {
    $state = "enabled=$($rule.Enabled), action=$($rule.Action), profile=$($rule.Profile), group=$($rule.Group)"
    if ($rule.Enabled -eq 'True' -and $rule.Action -eq 'Allow') { Write-Ok "Firewall rule '$RuleName' present ($state)" }
    else { Write-Bad "Firewall rule '$RuleName' exists but is not active ($state)"; $problems++ }
  } else { Write-Bad "Firewall rule '$RuleName' is missing"; $problems++ }
  $profiles = Get-NetConnectionProfile -ErrorAction SilentlyContinue
  foreach ($p in $profiles) { Write-Info "Network '$($p.InterfaceAlias)' is classified as $($p.NetworkCategory)" }

  # 5. third-party firewall managers
  $wfc = Get-Process -Name 'wfc', 'wfcs' -ErrorAction SilentlyContinue
  if (-not $wfc) { $wfc = Get-Service -Name 'wfcs' -ErrorAction SilentlyContinue }
  if ($wfc) {
    Write-Warn 'Malwarebytes Windows Firewall Control detected.'
    Write-Info "If 'Secure Rules' is enabled, it deletes rules outside authorized groups."
    Write-Info "-> WFC -> Security -> 'Define here a new authorized group' -> add '$FirewallGroup' -> click +"
  }
  $avFw = Get-CimInstance -Namespace root/SecurityCenter2 -ClassName FirewallProduct -ErrorAction SilentlyContinue
  foreach ($fw in $avFw) { Write-Warn "Third-party firewall registered: $($fw.displayName) - allow inbound TCP $ListenPort there as well." }

  # 6. scheduled task
  $task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
  if ($task) { Write-Ok "Scheduled task '$TaskName' present ($($task.State))" } else { Write-Warn "Scheduled task '$TaskName' not installed (settings may get lost after a reboot)" }

  # 7. local end-to-end test through the proxy
  try {
    $health = Invoke-WebRequest -Uri "http://127.0.0.1:$ListenPort/api/v1/health" -UseBasicParsing -TimeoutSec 5
    Write-Ok "Test through the proxy: http://127.0.0.1:$ListenPort/api/v1/health -> $($health.Content)"
  } catch { Write-Bad "Test through the proxy failed: $($_.Exception.Message)"; $problems++ }

  # 8. what to enter in ttv-tts.html
  Write-Step 'Use one of these in ttv-tts.html (CONFIG.vcp.baseUrl) on your OBS PC'
  $ips = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
    Where-Object { $_.IPAddress -notlike '127.*' -and $_.IPAddress -notlike '169.254.*' -and $_.PrefixOrigin -ne 'WellKnown' }
  foreach ($ip in $ips) { Write-Host ("  baseUrl: 'http://{0}:{1}',   ({2})" -f $ip.IPAddress, $ListenPort, $ip.InterfaceAlias) -ForegroundColor White }
  Write-Info 'Tip: give this PC a fixed IP (DHCP reservation in your router) so the address never changes.'

  Write-Host ''
  if ($problems -eq 0) { Write-Host 'Everything looks good. Test from the OBS PC with connection-check.html.' -ForegroundColor Green }
  else { Write-Host "$problems problem(s) found - see the [X] lines above and readme.html -> Network & firewall." -ForegroundColor Red }
}

try {
  if ($Uninstall) { Uninstall-Lan }
  elseif (-not $Check) { Install-Lan }
  if (-not $Uninstall) { Show-Status }
} catch {
  Write-Bad $_.Exception.Message
}
Wait-End
